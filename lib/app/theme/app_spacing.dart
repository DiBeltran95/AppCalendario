  /// Chips y badges.
  static const double chip = 12;

  /// Inputs y botones.
  static const double input = 16;

  /// Tarjetas.
  static const double card = 20;

  /// Bottom sheets y diálogos.
  static const double sheet = 28;

  /// Círculo completo.
  static const double full = 999;
}
